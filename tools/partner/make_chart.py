"""Writes the Partner's beat chart (game/scenes/chapters/partner/beat_chart.json)
from the bar-by-bar table in the draft song and beat chart, and checks it.

    python3 tools/partner/make_chart.py

The table below is the source; the JSON is generated. Edit here, re-run, commit both.
Draft: m1-prep/partner-song-and-beat-chart.md (not yet decided by Dan).

Dan, 2026-10-20, after playing the first build: "a little hard ... most people
should be able to get most beats on at least good, with less than 5 misses
during the whole run." So this chart is calmer than the draft's table: no two
notes closer than 500 ms (the draft had 250 ms), and the build-up comes from
more notes per bar, not faster ones. Dan, later the same day: "too singular beat
focused and boring, there needs to be some more variation in the beat, but as
long as it isn't too fast". So some notes fall halfway between beats, never
closer than 500 ms to the next.

Dan, 2026-10-21, asked for "a real crescendo": in the last bars (from bar 89)
more hearts come at once, in quarter-note triplets, three notes across two
beats, 333 ms apart. Only those bars are faster than 500 ms; everything before
stays as calm as it was.
"""
import json
import pathlib

BPM = 120
BEAT_MS = 60000 // BPM
BARS = 104
# Where bar 1, beat 1 falls in the song file. 0 for the placeholder song;
# measured in an audio editor for the real one.
START_OFFSET_MS = 0
INTRO_BARS = 8  # Intro taps set the player's sound delay and never laugh.

PATTERNS = {
    "H": [1, 3],          # Resting heartbeat, 60 a minute
    "S": [1, 3, 4],       # Heartbeat with a pickup into the next bar
    "Q": [1, 2, 3, 4],    # Every beat
    "D": [1, 2.5, 4],     # Dotted: the middle note falls between beats
    "T": [1, 2, 3.5],     # Two on the beat, then one between
    "P": [1, 2.5, 3.5],   # Push: two between the beats
    "O": [1.5, 3, 4],     # Starts just after the beat
    "W": [1, 1 + 2 / 3, 1 + 4 / 3, 3, 4],              # Crescendo: a triplet, then two beats
    "V": [1, 2, 3, 3 + 2 / 3, 3 + 4 / 3],              # Two beats, then a triplet
    "Z": [1, 1 + 2 / 3, 1 + 4 / 3, 3, 3 + 2 / 3, 3 + 4 / 3],  # Triplets all bar
    "X": [1],             # The last note
    "-": [],
}

# (first bar, patterns in order); a group repeats until the next first bar.
SECTIONS = [
    (1, "--"),
    (3, "HHHHHH"),
    (9, "HHHS" "HDHS" "HSHD" "HDSD" "HHDS" "HDHT"),
    (33, "QDQS" "DTDS" "QOQP" "DTQS" "QDOS" "PTQS"),
    (57, "QDQT" "QPQS" "OQDQ" "TQDS" "QDQP" "OQTS"),
    (81, "QDQT" "QPQQ"),
    (89, "WQVW" "VWZV" "WZZX"),
    (101, "----"),
]
SILENT_BARS = {48}  # The stumble: the band stops for one bar.
CRESCENDO_BAR = 89
NOTE_COUNT = 317


def bar_patterns():
    bars = {}
    for first, patterns in SECTIONS:
        for i, p in enumerate(patterns):
            bars[first + i] = "-" if first + i in SILENT_BARS else p
    assert sorted(bars) == list(range(1, BARS + 1)), "every bar needs a pattern"
    return bars


def main():
    notes = []
    for bar, p in sorted(bar_patterns().items()):
        for beat in PATTERNS[p]:
            notes.append(round(((bar - 1) * 4 + (beat - 1)) * BEAT_MS))

    # The checks the draft asks for, with Dan's 2026-10-20 easier chart.
    gaps = [b - a for a, b in zip(notes, notes[1:])]
    crescendo_ms = (CRESCENDO_BAR - 1) * 4 * BEAT_MS
    calm = [b - a for a, b in zip(notes, notes[1:]) if b <= crescendo_ms]
    assert len(notes) == NOTE_COUNT, len(notes)
    assert min(calm) >= 500, min(calm)
    assert min(gaps) >= 333, min(gaps)
    assert notes[-1] == (100 - 1) * 4 * BEAT_MS, notes[-1]

    chart = {
        "_comment": "Generated by tools/partner/make_chart.py. Times in ms from bar 1 beat 1; add start_offset_ms for the song file.",
        "bpm": BPM,
        "start_offset_ms": START_OFFSET_MS,
        "intro_end_ms": INTRO_BARS * 4 * BEAT_MS,
        "song_length_ms": BARS * 4 * BEAT_MS,
        # [start, end) in ms from bar 1 beat 1, where the band (and heartbeat) stops.
        "silent_ms": [[(b - 1) * 4 * BEAT_MS, b * 4 * BEAT_MS] for b in sorted(SILENT_BARS)],
        # Where the crescendo starts: denser notes, and the screen blooms.
        "crescendo_ms": crescendo_ms,
        "notes_ms": notes,
    }
    out = pathlib.Path(__file__).resolve().parents[2] / "game/scenes/chapters/partner/beat_chart.json"
    out.write_text(json.dumps(chart, indent=1) + "\n")
    print(f"{len(notes)} notes, closest gap {min(gaps)} ms, last at {notes[-1]} ms -> {out}")


if __name__ == "__main__":
    main()
